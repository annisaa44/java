    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txtNilaiAkhir.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Proses nilai dulu!");
            return;
        }

        String jk = rbLaki.isSelected() ? "LAKI-LAKI" : "PEREMPUAN";
        String baris = txtNim.getText() + " | " + txtNama.getText() + " | " + jk +
        " | Matkul: " + cbMatkul.getSelectedItem() + " | SKS: " + cbSks.getSelectedItem() +
        " | Absen: " + jTextField3.getText() + " | Tugas: " + txtTugas.getText() +
        " | UTS: " + txtUts.getText() + " | UAS: " + txtUas.getText() +
        " | Akhir: " + txtNilaiAkhir.getText() + " | Grade: " + txtGrade.getText() + "\n";

        txtAreaLog.append(baris);
    }//GEN-LAST:event_btnAddActionPerformed

