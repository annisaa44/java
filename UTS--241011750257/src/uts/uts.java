    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        try {
            int sks = Integer.parseInt(cbSks.getSelectedItem().toString());
            int maxPertemuan = (sks == 3) ? 21 : 14;
            double presensi = Double.parseDouble(jTextField3.getText());

            // Validasi pertemuan
            if (presensi > maxPertemuan) {
                javax.swing.JOptionPane.showMessageDialog(this, "Presensi melebihi maksimal pertemuan (" + maxPertemuan + ")!");
                return;
            }

            double tugas = Double.parseDouble(txtTugas.getText());
            double uts = Double.parseDouble(txtUts.getText());
            double uas = Double.parseDouble(txtUas.getText());

            // Rumus
            double persentaseAbsen = (presensi / maxPertemuan) * 100;
            double nilaiAbsen = persentaseAbsen * 0.10;
            double nilaiTugas = tugas * 0.20;
            double nilaiUts = uts * 0.30;
            double nilaiUas = uas * 0.40;
            double nilaiAkhir = nilaiAbsen + nilaiTugas + nilaiUts + nilaiUas;

            // Grade & Kondisi Absen < 75%
            String grade;
            if (persentaseAbsen < 75) {
                grade = "E";
            } else if (nilaiAkhir >= 80) {
                grade = "A";
            } else if (nilaiAkhir >= 60) {
                grade = "B";
            } else if (nilaiAkhir >= 40) {
                grade = "C";
            } else {
                grade = "E";
            }

            txtNilaiAkhir.setText(String.format(java.util.Locale.US, "%.2f", nilaiAkhir));
            txtGrade.setText(grade);

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Input harus angka!");
        }
    }//GEN-LAST:event_btnProsesActionPerformed

